#!/usr/bin/env python3
"""Generate or check the argument specs of the test-only community.docker shims.

The shims (ops/scripts/tests/fixtures/collections) must accept exactly the options
of the pinned community.docker modules. This script derives each argument spec
from `ansible-doc --json` of the pinned collection and either writes
plugins/module_utils/shim_specs.py (--write) or compares it (default).
"""
import json
import os
import pprint
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SHIM = Path(__file__).resolve().parent / "fixtures/collections/ansible_collections/community/docker"
SPECS = SHIM / "plugins/module_utils/shim_specs.py"
MODULES = ("docker_compose_v2", "docker_compose_v2_exec", "docker_container_info",
           "docker_host_info", "docker_image_pull")
KEYS = ("type", "required", "default", "choices", "aliases", "elements")


def normalize(options: dict) -> dict:
    spec = {}
    for name, option in sorted(options.items()):
        entry = {key: option[key] for key in KEYS if key in option}
        entry.setdefault("type", "str")
        if not entry.get("required", False):
            entry.pop("required", None)
        if "suboptions" in option:
            entry["options"] = normalize(option["suboptions"])
        spec[name] = entry
    return spec


def real_specs(collections: str) -> dict:
    env = dict(os.environ, ANSIBLE_COLLECTIONS_PATH=collections)
    specs = {}
    for module in MODULES:
        out = subprocess.run(["ansible-doc", "--json", "community.docker." + module], env=env,
                             check=True, capture_output=True, text=True).stdout
        doc = next(iter(json.loads(out).values()))["doc"]
        assert doc.get("collection", "community.docker") == "community.docker"
        specs[module] = normalize(doc["options"])
    return specs


def installed_version(collections: str) -> str:
    manifest = Path(collections) / "ansible_collections/community/docker/MANIFEST.json"
    return json.loads(manifest.read_text())["collection_info"]["version"]


def committed_specs() -> dict:
    scope: dict = {}
    exec(SPECS.read_text(), scope)  # noqa: S102 - trusted repository file
    return scope["SPECS"]


def main() -> int:
    collections = os.environ.get("AI_OPS_REAL_COLLECTIONS", str(ROOT / "ops/ansible/collections"))
    version = installed_version(collections)
    if version != "5.4.0":
        print(f"community.docker {version} installed; the shims track the pinned 5.4.0", file=sys.stderr)
        return 1
    real = real_specs(collections)
    if "--write" in sys.argv:
        SPECS.write_text('"""Generated by ops/scripts/tests/docker_shim_specs.py --write; do not edit."""\n'
                         "SPECS = " + pprint.pformat(real, width=110, sort_dicts=True) + "\n")
        return 0
    problems = compare(committed_specs(), real)
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


def compare(committed: dict, real: dict) -> list:
    problems = []
    for module in MODULES:
        if committed.get(module) != real[module]:
            missing = sorted(set(real[module]) - set(committed.get(module, {})))
            extra = sorted(set(committed.get(module, {})) - set(real[module]))
            problems.append(f"{module}: shim spec differs (missing={missing} extra={extra})")
    return problems


if __name__ == "__main__":
    sys.exit(main())
